import { beforeEach, describe, expect, test } from 'bun:test';
import { z } from 'zod/v4';
import { type Infer, create, embedded, expr, from, into, t, table } from '../src';
import { type Database, type Equals, type RequiredKeys, assert, suite } from './helpers';

const things = table('things', {
  seq: t.sequence().primaryKey(),
  blob: t.binary().optional(),
  flag: t.boolean().default(false),
  day: t.date(),
  amount: t.decimal(),
  price: t.decimal({ precision: 10, scale: 2 }).optional(),
  ratio: t.float(),
  count: t.integer(),
  huge: t.bigint().optional(),
  label: t.citext().optional(),
  code: t.string({ size: 8 }).optional(),
  body: t.text(),
  doc: t.json(z.object({ a: z.array(z.number()) })),
  meta: embedded.one({ huge: t.bigint(), day: t.date(), blob: t.binary(), active: t.boolean() }).optional(),
});

type Thing = Infer<'select', typeof things>;
type ThingInsert = Infer<'insert', typeof things>;

const thing = (overrides: Partial<ThingInsert> = {}): ThingInsert => ({
  day: '2026-11-14',
  amount: 1.5,
  ratio: 0.25,
  count: 7,
  body: 'body',
  doc: { a: [1, 2] },
  ...overrides,
});

const HUGE = 2n ** 60n;

suite('primitive types', (fresh) => {
  let db: Database;
  let sqls: string[];

  beforeEach(async () => {
    ({ db, sqls } = await fresh());
    await create.table(things).onto(db);
    sqls.length = 0;
  });

  test('round-trip every type', async () => {
    const row = thing({
      blob: new Uint8Array([0, 1, 255]),
      flag: true,
      price: 12.34,
      huge: HUGE,
      label: 'Hello',
      code: 'abcdefgh',
      meta: { huge: HUGE, day: '2024-02-29', blob: new Uint8Array([9, 8]), active: true },
    });

    const [inserted] = await into(things).values(row).insert(db);

    expect(inserted).toEqual({ seq: 1, ...row } as Thing);
    expect(await from(things).all(db)).toEqual([inserted!]);
  });

  test('round-trip every type through an aggregate', async () => {
    const meta = { huge: HUGE, day: '2024-02-29', blob: new Uint8Array([9, 8]), active: true };
    const inserted = await into(things).values([
      thing({ blob: new Uint8Array([0, 1, 255]), flag: true, price: 12.34, huge: HUGE, label: 'Hello', code: 'abcdefgh', meta }),
      thing(),
    ]).insert(db);

    const row = await from(things).select({ all: expr.aggregate(things) }).one(db);

    expect(row!.all.toSorted((x, y) => x.seq - y.seq)).toEqual(inserted);
  });

  test('fill in nulls and defaults', async () => {
    const [inserted] = await into(things).values(thing()).insert(db);

    expect(inserted).toMatchObject({ blob: null, flag: false, price: null, huge: null, label: null, code: null, meta: null });
  });

  describe('t.sequence()', () => {
    test('is generated by the database, counting up', async () => {
      const inserted = await into(things).values([thing(), thing(), thing()]).insert(db, { returning: ['seq'] });

      expect(inserted).toEqual([{ seq: 1 }, { seq: 2 }, { seq: 3 }]);
      expect(sqls.at(-1)).not.toContain('"seq", ');
    });
  });

  describe('t.boolean()', () => {
    beforeEach(async () => {
      await into(things).values([thing({ flag: true }), thing({ flag: false })]).insert(db);
    });

    const flags = async (op: 'IS' | 'IS NOT', value: boolean) =>
      (await from(things).where(things.flag, op, value).select({ flag: things.flag }).all(db)).map(row => row.flag);

    test('IS TRUE and IS FALSE', async () => {
      expect(await flags('IS', true)).toEqual([true]);
      expect(await flags('IS', false)).toEqual([false]);
    });

    test('IS NOT TRUE and IS NOT FALSE', async () => {
      expect(await flags('IS NOT', true)).toEqual([false]);
      expect(await flags('IS NOT', false)).toEqual([true]);
    });

    test('IS TRUE and IS FALSE on nested fields', async () => {
      const meta = { huge: 1n, day: '2026-11-14', blob: new Uint8Array() };
      await into(things).values([thing({ meta: { ...meta, active: true } }), thing({ meta: { ...meta, active: false } })]).insert(db);

      expect(await from(things).where(things.meta.active, 'IS', true).select({ active: things.meta.active }).all(db)).toEqual([{ active: true }]);
      // unlike `!=`, `IS NOT` matches nulls too
      expect(await from(things).where(things.meta.active, 'IS NOT', true).orderBy([things.seq]).select({ active: things.meta.active }).all(db)).toEqual([{ active: null }, { active: null }, { active: false }]);
    });

    test('rejects anything but null, true and false', async () => {
      expect(() => from(things).where(things.flag, 'IS', JSON.parse('1'))).toThrow('"IS" takes null, true or false, got 1');
    });
  });

  describe('t.bigint()', () => {
    test('keeps values beyond 2^53 exact', async () => {
      await into(things).values([thing({ huge: HUGE }), thing({ huge: HUGE + 1n })]).insert(db);

      const rows = await from(things).where(things.huge, '>', HUGE).select({ huge: things.huge }).all(db);

      expect(rows).toEqual([{ huge: HUGE + 1n }]);
    });
  });

  describe('t.citext()', () => {
    test('compares case-insensitively', async () => {
      await into(things).values(thing({ label: 'Hello' })).insert(db);

      expect(await from(things).where(things.label, '=', 'HELLO').count(db)).toBe(1);
    });
  });

  describe('t.string()', () => {
    test('rejects values longer than its size', async () => {
      await expect(into(things).values(thing({ code: 'abcdefghi' })).insert(db)).rejects.toThrow();
    });
  });

  describe('t.date()', () => {
    test('orders by date', async () => {
      await into(things).values([thing({ day: '2026-11-14' }), thing({ day: '2025-01-31' })]).insert(db);

      const rows = await from(things).orderBy([things.day]).select({ day: things.day }).all(db);

      expect(rows).toEqual([{ day: '2025-01-31' }, { day: '2026-11-14' }]);
    });

    test('rejects impossible dates', async () => {
      await expect(into(things).values(thing({ day: '2026-02-30' })).insert(db)).rejects.toThrow();
    });
  });

  describe('t.decimal()', () => {
    test('compares as a number', async () => {
      await into(things).values([thing({ price: 9.99 }), thing({ price: 10.01 })]).insert(db);

      expect(await from(things).where(things.price, '>', 10).select({ price: things.price }).all(db)).toEqual([{ price: 10.01 }]);
    });
  });

  describe('t.binary()', () => {
    test('rejects anything but bytes', async () => {
      await expect(into(things).values(thing({ blob: JSON.parse('[1,2]') })).insert(db)).rejects.toThrow();
    });
  });

  describe('t.json()', () => {
    test('validates documents with its schema', async () => {
      await expect(into(things).values(thing({ doc: JSON.parse('{"a":["x"]}') })).insert(db)).rejects.toThrow();
    });
  });

  describe('embedded fields', () => {
    test('can be bigints, dates and binaries', async () => {
      const meta = { huge: HUGE, day: '2026-11-14', blob: new Uint8Array([1, 2, 3]), active: false };
      await into(things).values([thing({ meta }), thing({ meta: { ...meta, huge: 1n } })]).insert(db);

      const rows = await from(things).where(things.meta.huge, '=', HUGE).select({ meta: things.meta, day: things.meta.day }).all(db);

      expect(rows).toEqual([{ meta, day: '2026-11-14' }]);
    });
  });
});

// ─── type-level ──────────────────────────────────────────────────────────────

type Bytes = InstanceType<typeof Uint8Array>;

assert<Equals<Thing, {
  seq: number;
  blob: Bytes | null;
  flag: boolean;
  day: string;
  amount: number;
  price: number | null;
  ratio: number;
  count: number;
  huge: bigint | null;
  label: string | null;
  code: string | null;
  body: string;
  doc: { a: number[] };
  meta: { huge: bigint; day: string; blob: Bytes; active: boolean } | null;
}>>();

// sequences are generated, so they're neither inserted nor updated
assert<Equals<RequiredKeys<ThingInsert>, 'day' | 'amount' | 'ratio' | 'count' | 'body' | 'doc'>>();
assert<Equals<'seq' extends keyof Infer<'update', typeof things> ? true : false, false>>();

export const typeChecks = async (db: Database) => {
  // @ts-expect-error sequences are generated by the database
  into(things).values({ ...thing(), seq: 1 });

  // @ts-expect-error decimals can't have a scale without a precision
  t.decimal({ scale: 2 });

  // @ts-expect-error decimals can't have a precision without a scale
  t.decimal({ precision: 10 });

  // @ts-expect-error bigints take bigints, not numbers
  from(things).where(things.huge, '>', 1);

  // @ts-expect-error dates are YYYY-MM-DD strings, not Dates
  into(things).values(thing({ day: new Date() }));

  // `IS` and `IS NOT` take booleans for booleans, and null for nullable values
  from(things).where(things.flag, 'IS', true).where(things.flag, 'IS NOT', false);
  from(things).where(things.label, 'IS', null).where(expr(things.meta.active, 'IS', false));

  // fields nested in an optional column read null when the column is
  const active = await from(things).select({ active: things.meta.active }).all(db);
  assert<Equals<typeof active, { active: boolean | null }[]>>();

  // @ts-expect-error only nullable values can be tested for null
  from(things).where(things.flag, 'IS', null);

  // @ts-expect-error only booleans can be tested for true or false
  from(things).where(things.label, 'IS', true);

  // bigint and decimal columns can be incremented
  from(things).update(db, { inc: { huge: 1, amount: 0.5 } });
};
